#!/usr/bin/env node
/**
 * Build scripts/routing/cloud-init-brouter.yaml from the template plus every
 * profile in scripts/routing/profiles/. The profiles in the repo are the
 * single source of truth; the server gets exact copies at provision time.
 *
 *   node scripts/routing/build-cloud-init.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const template = readFileSync(join(here, "cloud-init-brouter.template.yaml"), "utf8");
const profilesDir = join(here, "profiles");
const files = readdirSync(profilesDir).filter((f) => f.endsWith(".brf")).sort();

// Hetzner user_data is limited to 32 KiB. Only the strict profile is
// embedded; loops-road-relaxed is DERIVED on the server from it with the
// same edits the repo copy was generated with (verified identical below).
const RELAXED_EDITS = [
  ["  switch or highway=trunk highway=trunk_link          60.0\n", "  switch or highway=trunk highway=trunk_link          15.0\n"],
  ["  switch or highway=primary highway=primary_link      30.0\n", "  switch or highway=primary highway=primary_link      8.0\n"],
  ["cycleway:both=track\n         20.0\n  switch and maxspeed=80|90\n", "cycleway:both=track\n         6.0\n  switch and maxspeed=80|90\n"],
  ["             not or highway=cycleway or cycleway=track or cycleway:left=track or cycleway:right=track cycleway:both=track\n         20.0\n  # Rule 4", "             not or highway=cycleway or cycleway=track or cycleway:left=track or cycleway:right=track cycleway:both=track\n         6.0\n  # Rule 4"],
  ["  # ── LOOPS ROAD STANDARD (CEO, 2026-09-21) ────────────────────────────────\n  # Rule 1: no main roads. Motorways impossible; trunk/primary cost 60x/30x —\n", "  # ── LOOPS ROAD STANDARD — RELAXED FALLBACK (see header) ─────────────────\n  # Rule 1: main roads are a last resort (motorways still forbidden).\n  # trunk/primary cost 60x/30x —\n"],
];
function deriveRelaxed(strict) {
  let out = strict;
  for (const [a, b] of RELAXED_EDITS) {
    if (out.split(a).length !== 2) throw new Error(`relaxed edit anchor not found exactly once: ${a.slice(0, 50)}`);
    out = out.replace(a, b);
  }
  return out;
}
{
  // The repo copy of loops-road-relaxed.brf is GENERATED here from
  // loops-road.brf so it can never drift from what the server derives.
  const strict = readFileSync(join(profilesDir, "loops-road.brf"), "utf8");
  const header = [
    "#",
    "# loops-road-relaxed — FALLBACK ONLY. GENERATED by scripts/routing/build-cloud-init.mjs",
    "# from loops-road.brf; edit loops-road.brf (or RELAXED_EDITS in the builder), never this file.",
    "#",
    "# Identical to loops-road except that main roads (primary 8x, trunk 15x)",
    "# and fast roads (6x) are cheaper. Unpaved surfaces, tracks, paths, footways,",
    "# steps and motorways stay impossible — a road bike on gravel is never a",
    "# compromise. The app tries loops-road first; only when that finds no sane",
    "# route does it try this profile, and it then measures and names every",
    "# non-standard stretch or refuses the route if the compromise is too long.",
    "#",
    "",
  ].join("\n");
  writeFileSync(join(profilesDir, "loops-road-relaxed.brf"), header + deriveRelaxed(strict));
}
const embedded = files.filter((f) => f !== "loops-road-relaxed.brf");

const blocks = embedded.map((f) => {
  const body = readFileSync(join(profilesDir, f), "utf8").replace(/\s+$/, "");
  const indented = body.split("\n").map((l) => (l.length ? "      " + l : "")).join("\n");
  return `  - path: /opt/brouter/profiles/${f}\n    permissions: "0644"\n    content: |\n${indented}\n`;
});

// Derivation script for the server (python3 ships with cloud-init images).
const pyEdits = JSON.stringify(RELAXED_EDITS);
const derive = [
  "  - path: /opt/brouter/profiles/derive-relaxed.py",
  '    permissions: "0755"',
  "    content: |",
  "      #!/usr/bin/env python3",
  "      # Derive loops-road-relaxed.brf from loops-road.brf (same edits as",
  "      # scripts/routing/build-cloud-init.mjs — kept in one place).",
  "      import json, sys",
  `      EDITS = json.loads(${JSON.stringify(pyEdits)})`,
  "      s = open('/opt/brouter/profiles/loops-road.brf').read()",
  "      for a, b in EDITS:",
  "          assert s.count(a) == 1, a[:50]",
  "          s = s.replace(a, b)",
  "      open('/opt/brouter/profiles/loops-road-relaxed.brf', 'w').write(s)",
  "      print('loops-road-relaxed.brf derived')",
  "",
].join("\n");

const out = template.replace("#__PROFILES__\n", blocks.join("") + derive);
if (Buffer.byteLength(out, "utf8") > 32 * 1024) {
  throw new Error(`cloud-init is ${Buffer.byteLength(out, "utf8")} bytes — over Hetzner's 32 KiB user_data limit`);
}
writeFileSync(join(here, "cloud-init-brouter.yaml"), out);

// The same profiles as JSON for the app: POST /api/engine/sync-profiles
// uploads them to the live engine (custom profile ids) without a rebuild.
const asJson = Object.fromEntries(files.map((f) => [f.replace(/\.brf$/, ""), readFileSync(join(profilesDir, f), "utf8")]));
writeFileSync(join(here, "..", "..", "src", "data", "engine-profiles.json"), JSON.stringify(asJson));
console.log(`cloud-init-brouter.yaml: ${embedded.length} profile(s) embedded (${embedded.join(", ")}) + relaxed derived on the server, ${(Buffer.byteLength(out, "utf8") / 1024).toFixed(1)} KB (limit 32)`);
